(function() {
  if (window.skillsPageInitialized) return;
  window.skillsPageInitialized = true;

  document.addEventListener("DOMContentLoaded", function() {
    var container = document.getElementById('skills-container');
    if (!container) return;

    var feedUrl = container.getAttribute('data-feed-url');
    var skillsUrl = container.getAttribute('data-skills-url');

    fetch(feedUrl)
      .then(function(response) {
        if (!response.ok) {
          throw new Error('Failed to fetch skills feed: ' + response.status + ' ' + response.statusText);
        }
        return response.json();
      })
      .then(function(data) {
        if (!Array.isArray(data)) throw new Error('Skills feed JSON is not an array');

        var skillsMap = {};

        data.forEach(function(doc) {
          if (doc.tags && Array.isArray(doc.tags)) {
            doc.tags.forEach(function(tag) { addSkillToMap(skillsMap, tag, doc); });
          }

          var tempDiv = document.createElement('div');
          tempDiv.innerHTML = doc.content;
          tempDiv.querySelectorAll('.cv-skill-tag').forEach(function(tagElem) {
            var skillName = tagElem.getAttribute('data-skill');
            if (skillName) addSkillToMap(skillsMap, skillName, doc);
          });
        });

        renderSkills(skillsMap);
      })
      .catch(function(err) {
        console.error('Error loading skills:', err);
        container.innerHTML = '<p>Error: <code>/assets/skills-feed.json</code> not found.</p>' +
          '<p>This file is generated by a script during the site build process. ' +
          'If you are running the site locally, please make sure you have run the script to generate this file. ' +
          'If this is a live site, the file was not generated during the build.</p>';
      });

    function addSkillToMap(map, skillName, doc) {
      var cleanName = skillName.trim();
      if (!map[cleanName]) map[cleanName] = [];
      if (!map[cleanName].some(function(item) { return item.url === doc.url; })) {
        map[cleanName].push({
          title: doc.title,
          venue: doc.venue,
          url: doc.url
        });
      }
    }

    function renderSkills(map) {
      if (container.children.length > 0 && container.querySelector('.skill-section')) {
        return;
      }

      container.innerHTML = '';

      var urlParams = new URLSearchParams(window.location.search);
      var activeTag = urlParams.get('tag');
      if (activeTag) {
        activeTag = activeTag.replace(/\+/g, ' ').trim();
      }

      var keysToRender = Object.keys(map).sort(function(a, b) { return a.localeCompare(b); });
      var isFiltered = false;

      if (activeTag) {
        var matchedKey = keysToRender.find(function(k) { return k === activeTag; });
        if (!matchedKey) {
          matchedKey = keysToRender.find(function(k) { return k.toLowerCase() === activeTag.toLowerCase(); });
        }

        if (matchedKey) {
          keysToRender = [matchedKey];
          isFiltered = true;

          var backBtn = document.createElement('a');
          backBtn.href = skillsUrl;
          backBtn.className = 'btn btn--inverse';
          backBtn.style.display = 'inline-block';
          backBtn.style.marginBottom = '20px';
          backBtn.style.textDecoration = 'none';
          backBtn.innerHTML = '&larr; Back to all skills';
          backBtn.setAttribute('data-smooth-scroll', 'false');
          container.appendChild(backBtn);

          var header = document.createElement('h2');
          header.textContent = matchedKey;
          container.appendChild(header);
        } else {
          var strong = document.createElement('strong');
          strong.textContent = activeTag;
          container.innerHTML = '<p>No projects found for skill: </p>';
          container.querySelector('p').appendChild(strong);
          var viewAllLink = document.createElement('a');
          viewAllLink.href = skillsUrl;
          viewAllLink.textContent = 'View all skills';
          container.appendChild(viewAllLink);
          return;
        }
      }

      if (keysToRender.length === 0) {
        container.innerHTML = '<p>No skills found. Add tags to your posts, projects, or publications to see them here.</p>';
        return;
      }

      keysToRender.forEach(function(skill) {
        var section = document.createElement('div');
        section.className = 'skill-section';
        section.style.marginBottom = '30px';

        if (!isFiltered) {
          var title = document.createElement('h2');
          title.id = encodeURIComponent(skill);
          title.textContent = skill;
          title.style.borderBottom = "1px solid #eaeaea";
          title.style.paddingBottom = "10px";
          section.appendChild(title);
        }

        var list = document.createElement('ul');
        map[skill].forEach(function(project) {
          var li = document.createElement('li');
          var link = document.createElement('a');
          link.href = project.url;
          var titleSpan = document.createElement('strong');
          titleSpan.textContent = project.title || 'Untitled';
          link.appendChild(titleSpan);
          link.setAttribute('data-smooth-scroll', 'false');
          li.appendChild(link);

          if (project.venue) {
            var venueSpan = document.createElement('span');
            venueSpan.style.color = '#666';
            venueSpan.style.fontSize = '0.9em';
            venueSpan.textContent = ' \u2014 ' + project.venue;
            li.appendChild(venueSpan);
          }
          list.appendChild(li);
        });

        section.appendChild(list);
        container.appendChild(section);
      });
    }
  });
})();
